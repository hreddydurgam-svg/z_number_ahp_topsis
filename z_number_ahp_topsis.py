print(f"{'Criteria':<16} | {'Std_MC_Mean':<13} | {'Std_MC_StdDev':<15} || {'ZNum_Mean':<12} | {'ZNum_StdDev':<12}")
print("-" * 85)

summary_data = []
final_znum_weights = {}

for criteria in criteria_cols:
    # Standard Monte Carlo Results (Actual numeric noise from uniform distributions)
    std_mean = df_std[criteria].mean()
    std_std = df_std[criteria].std()

    # Z-Number Results (True Empirical Population Parameters)
    znum_mean = df_znum[criteria].mean()
    znum_std = df_znum[criteria].std()

    final_znum_weights[criteria] = znum_mean

    print(f"{criteria:<16} | {std_mean:>13.4f} | ± {std_std:>13.4f} || {znum_mean:>12.4f} | ± {znum_std:>10.4f}")

    # Append for high-precision CSV export
    summary_data.append({
        'Criteria': criteria,
        'Std_MC_Mean': round(std_mean, 6),
        'Std_MC_StdDev': round(std_std, 6),
        'ZNum_Mean': round(znum_mean, 6),
        'ZNum_StdDev': round(znum_std, 6)
    })

